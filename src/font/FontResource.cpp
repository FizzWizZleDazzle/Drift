struct FontResource::Impl {
    RendererResource& renderer;
    HandlePool<FontTag, std::shared_ptr<FontData>> fonts;
    FontHandle defaultFont;
    GlyphAtlas linearAtlas;
    GlyphAtlas nearestAtlas;
    std::unordered_map<uint64_t, CachedGlyph> cache;
    std::vector<uint8_t> scratch, scratch2;
    Layout drawLayout;
    float outScale = 1.f;
    bool atlasFullLogged = false;

    explicit Impl(RendererResource& r)
        : renderer(r), linearAtlas(r, TextureFilter::Linear), nearestAtlas(r, TextureFilter::Nearest) {}

    FontData* get(FontHandle h) {
        auto* p = fonts.get(h.valid() ? h : defaultFont);
        return p ? p->get() : nullptr;
    }

    FontHandle add(std::shared_ptr<FontData> f) {
        FontHandle h = fonts.create(f);
        f->key = h.index();
        if (defaultFont.valid()) f->fallback = defaultFont;
        return h;
    }

    GlyphAtlas& atlasFor(const FontData& f) {
        return f.filter == TextureFilter::Nearest ? nearestAtlas : linearAtlas;
    }

    // ---- loading ----------------------------------------------------------

    FontHandle loadTrueType(const uint8_t* data, size_t size, float sizePx,
                            const FontOptions& options, const char* name) {
        if (!data || size < 12) {   // smaller than an sfnt header
            DRIFT_LOG_ERROR("loadFont '%s': not a TrueType/OpenType font", name);
            return {};
        }
        if (sizePx <= 0.f) {
            DRIFT_LOG_ERROR("loadFont '%s': size must be positive", name);
            return {};
        }
        auto f = std::make_shared<FontData>();
        f->ttf.assign(data, data + size);
        int offset = stbtt_GetFontOffsetForIndex(f->ttf.data(), 0);
        if (offset < 0 || !stbtt_InitFont(&f->info, f->ttf.data(), offset)) {
            DRIFT_LOG_ERROR("loadFont '%s': not a TrueType/OpenType font", name);
            return {};
        }
        int a = 0, d = 0, g = 0;
        stbtt_GetFontVMetrics(&f->info, &a, &d, &g);
        f->ascent = static_cast<float>(a);
        f->descent = static_cast<float>(d);
        f->lineGap = static_cast<float>(g);
        f->loadSize = sizePx;
        f->filter = options.filter.value_or(TextureFilter::Linear);
        return add(std::move(f));
    }

    FontHandle loadBitmapFont(const char* path, std::string_view text, float sizePx,
                              const FontOptions& options) {
        auto f = std::make_shared<FontData>();
        std::string error;
        if (!parseBMFont(text, f->bm, error)) {
            DRIFT_LOG_ERROR("loadFont '%s': %s", path, error.c_str());
            return {};
        }
        f->bitmap = true;
        f->filter = options.filter.value_or(TextureFilter::Nearest);
        f->loadSize = sizePx > 0.f ? sizePx : f->bm.size;

        std::string dir(path);
        size_t slash = dir.find_last_of("/\\");
        dir = slash == std::string::npos ? std::string() : dir.substr(0, slash + 1);

        TextureOptions texOpts;
        texOpts.filter = f->filter;
        for (const std::string& file : f->bm.pages) {
            std::string pagePath = dir + file;
            size_t bytes = 0;
            void* data = file.empty() ? nullptr : SDL_LoadFile(pagePath.c_str(), &bytes);
            if (!data) {
                DRIFT_LOG_ERROR("loadFont '%s': cannot read page '%s'", path, pagePath.c_str());
                for (TextureHandle t : f->pages) renderer.destroyTexture(t);
                return {};
            }
            int w = 0, h = 0, n = 0;
            uint8_t* px = stbi_load_from_memory(static_cast<const stbi_uc*>(data),
                                                static_cast<int>(bytes), &w, &h, &n, 4);
            SDL_free(data);
            if (!px) {
                DRIFT_LOG_ERROR("loadFont '%s': cannot decode page '%s'", path, pagePath.c_str());
                for (TextureHandle t : f->pages) renderer.destroyTexture(t);
                return {};
            }
            FontData::PagePixels page;
            page.w = w;
            page.h = h;
            page.rgba.assign(px, px + static_cast<size_t>(w) * h * 4);
            stbi_image_free(px);
            // Grayscale pages carry the glyph in luminance: white text,
            // gray as alpha.
            if (n == 1) {
                for (size_t i = 0; i < page.rgba.size(); i += 4) {
                    page.rgba[i + 3] = page.rgba[i];
                    page.rgba[i] = page.rgba[i + 1] = page.rgba[i + 2] = 255;
                }
            }
            f->pages.push_back(renderer.createTextureFromPixels(page.rgba.data(), w, h, texOpts));
            f->pagePixels.push_back(std::move(page));
        }
        return add(std::move(f));
    }

    // ---- glyph lookup -----------------------------------------------------

    int findGlyph(FontData& f, uint32_t cp) {
        if (f.bitmap) return f.bm.chars.count(cp) ? static_cast<int>(cp) : -1;
        auto it = f.glyphIndex.find(cp);
        if (it == f.glyphIndex.end()) {
            int g = stbtt_FindGlyphIndex(&f.info, static_cast<int>(cp));
            it = f.glyphIndex.emplace(cp, g > 0 ? g : -1).first;
        }
        return it->second;
    }

    // The font and glyph that draw cp: the font itself, then its fallback
    // chain, then the primary font's missing-glyph shape.
    bool resolve(FontData& primary, uint32_t cp, FontData*& font, int& glyph) {
        FontData* f = &primary;
        for (int depth = 0; f && depth < 4; ++depth) {
            int g = findGlyph(*f, cp);
            if (g >= 0) { font = f; glyph = g; return true; }
            auto* next = fonts.get(f->fallback);   // empty handle = no fallback
            f = next ? next->get() : nullptr;
            if (f == &primary) break;
        }
        if (!primary.bitmap) { font = &primary; glyph = 0; return true; }
        int q = findGlyph(primary, '?');
        if (q >= 0) { font = &primary; glyph = q; return true; }
        return false;
    }

    float advance(const FontData& f, int glyph, float scale) {
        if (f.bitmap) return f.bm.chars.at(static_cast<uint32_t>(glyph)).xadvance * scale;
        int adv = 0, lsb = 0;
        stbtt_GetGlyphHMetrics(&f.info, glyph, &adv, &lsb);
        return static_cast<float>(adv) * scale;
    }

    float kern(const FontData& f, int a, int b, float scale) {
        if (f.bitmap) {
            auto it = f.bm.kerning.find((static_cast<uint64_t>(a) << 32) | static_cast<uint32_t>(b));
            return it == f.bm.kerning.end() ? 0.f : it->second * scale;
        }
        return static_cast<float>(stbtt_GetGlyphKernAdvance(&f.info, a, b)) * scale;
    }

    // ---- layout -----------------------------------------------------------

    // Handles a '[' at text[i] in rich text. Returns true if a tag was
    // consumed; "[[" consumes one '[' and returns false so the next '['
    // is drawn.
    static bool parseTag(std::string_view text, size_t& i, std::vector<Color>& stack,
                         Color& cur, Color base) {
        std::string_view rest = text.substr(i);
        if (rest.substr(0, 2) == "[[") { ++i; return false; }
        if (rest.substr(0, 8) == "[/color]") {
            if (!stack.empty()) { cur = stack.back(); stack.pop_back(); }
            i += 8;
            return true;
        }
        if (rest.substr(0, 8) != "[color=#") return false;
        size_t close = rest.find(']');
        if (close == std::string_view::npos) return false;
        std::string_view hex = rest.substr(8, close - 8);
        if (hex.size() != 6 && hex.size() != 8) return false;
        uint8_t ch[4] = {0, 0, 0, 255};
        for (size_t k = 0; k < hex.size(); k += 2) {
            int hi = hexDigit(hex[k]), lo = hexDigit(hex[k + 1]);
            if (hi < 0 || lo < 0) return false;
            ch[k / 2] = static_cast<uint8_t>(hi * 16 + lo);
        }
        stack.push_back(cur);
        cur = Color(ch[0], ch[1], ch[2], static_cast<uint8_t>(ch[3] * base.a / 255));
        i += close + 1;
        return true;
    }

    void layout(FontData& primary, std::string_view text, const TextStyle& st, Layout& out) {
        out.glyphs.clear();
        out.lines.clear();
        float size = st.size > 0.f ? st.size : primary.loadSize;
        Metrics pm = metricsFor(primary, size);
        out.size = size;
        out.ascent = pm.ascent;
        out.lineHeight = pm.lineHeight;
        out.lineAdvance = pm.lineHeight * st.lineSpacing;
        out.width = out.height = 0.f;
        if (text.empty()) return;

        std::vector<Color> colors;
        Color cur = st.color;
        FontData* prevFont = nullptr;
        int prevGlyph = -1;
        float pen = 0.f;
        size_t lineStart = 0;

        size_t i = 0;
        while (i < text.size()) {
            if (st.richText && text[i] == '[' && parseTag(text, i, colors, cur, st.color)) continue;
            uint32_t cp = decodeUtf8(text, i);
            if (cp == '\n') {
                wrap(out, lineStart, out.glyphs.size(), st.wrapWidth);
                lineStart = out.glyphs.size();
                pen = 0.f;
                prevFont = nullptr;
                continue;
            }
            bool tab = cp == '\t';
            if (tab) cp = ' ';
            else if (cp < 0x20 || (cp >= 0x7F && cp < 0xA0)) continue;

            FontData* f = nullptr;
            int g = -1;
            if (!resolve(primary, cp, f, g)) continue;
            float scale = f == &primary ? pm.scale : metricsFor(*f, size).scale;
            if (f == prevFont) pen += kern(*f, prevGlyph, g, scale);
            float adv = advance(*f, g, scale) * (tab ? 4.f : 1.f);
            out.glyphs.push_back({f, static_cast<uint32_t>(g), pen, adv, cur,
                                  cp == ' ' || cp == 0x3000});
            pen += adv;
            prevFont = f;
            prevGlyph = g;
        }
        wrap(out, lineStart, out.glyphs.size(), st.wrapWidth);

        for (const Line& l : out.lines) out.width = std::max(out.width, l.width);
        out.height = out.lineHeight + static_cast<float>(out.lines.size() - 1) * out.lineAdvance;
    }

    static void emitLine(Layout& out, size_t s, size_t e) {
        size_t end = e;
        while (end > s && out.glyphs[end - 1].space) --end;
        float x0 = s < out.glyphs.size() ? out.glyphs[s].x : 0.f;
        float w = end > s ? out.glyphs[end - 1].x + out.glyphs[end - 1].advance - x0 : 0.f;
        out.lines.push_back({s, end, w, x0});
    }

    // Splits glyphs [begin, end) (one hard line) into lines no wider than
    // width: at the last space that fits, or inside a word that alone is
    // too wide.
    static void wrap(Layout& out, size_t begin, size_t end, float width) {
        if (width <= 0.f) { emitLine(out, begin, end); return; }
        size_t start = begin;
        size_t lastSpace = SIZE_MAX;
        size_t i = begin;
        while (i < end) {
            const Shaped& g = out.glyphs[i];
            if (g.space) { lastSpace = i++; continue; }
            float right = g.x + g.advance - out.glyphs[start].x;
            if (right <= width || i == start) { ++i; continue; }
            size_t breakAt, next;
            if (lastSpace != SIZE_MAX && lastSpace > start) {
                breakAt = lastSpace;
                next = lastSpace + 1;
            } else {
                breakAt = i;
                next = i;
            }
            emitLine(out, start, breakAt);
            while (next < end && out.glyphs[next].space) ++next;
            start = next;
            lastSpace = SIZE_MAX;
            i = start;
        }
        emitLine(out, start, end);
    }

    // ---- rasterization ----------------------------------------------------

    CachedGlyph store(GlyphAtlas& atlas, const uint8_t* px, int w, int h, float offX, float offY) {
        CachedGlyph e;
        GlyphAtlas::Region reg;
        if (!atlas.allocate(w, h, reg)) {
            if (!atlasFullLogged) {
                DRIFT_LOG_WARN("font: glyph of %dx%d does not fit the atlas", w, h);
                atlasFullLogged = true;
            }
            return e;
        }
        atlas.writeAlpha(reg, px, w);
        e.texture = reg.texture;
        e.src = {static_cast<float>(reg.x), static_cast<float>(reg.y),
                 static_cast<float>(w), static_cast<float>(h)};
        e.offX = offX;
        e.offY = offY;
        e.empty = false;
        return e;
    }

    CachedGlyph rasterTrueType(FontData& f, int glyph, int raster, int r) {
        float s = stbtt_ScaleForPixelHeight(&f.info, static_cast<float>(raster));
        int x0 = 0, y0 = 0, x1 = 0, y1 = 0;
        stbtt_GetGlyphBitmapBox(&f.info, glyph, s, s, &x0, &y0, &x1, &y1);
        int w = x1 - x0, h = y1 - y0;
        if (w <= 0 || h <= 0) return {};
        int pad = 1 + r;   // 1 transparent pixel so linear filtering fades out
        int W = w + 2 * pad, H = h + 2 * pad;
        scratch.assign(static_cast<size_t>(W) * H, 0);
        stbtt_MakeGlyphBitmap(&f.info, scratch.data() + pad * W + pad, w, h, W, s, s, glyph);
        const uint8_t* px = scratch.data();
        if (r > 0) {
            dilate(scratch, W, H, r, scratch2);
            px = scratch2.data();
        }
        return store(atlasFor(f), px, W, H, static_cast<float>(x0 - pad), static_cast<float>(y0 - pad));
    }

    CachedGlyph rasterBitmapOutline(FontData& f, uint32_t cp, int r) {
        const BMFontDesc::Char& c = f.bm.chars.at(cp);
        if (c.w <= 0 || c.h <= 0 || c.page < 0 || c.page >= static_cast<int>(f.pagePixels.size())) return {};
        const auto& page = f.pagePixels[c.page];
        int pad = 1 + r;
        int W = c.w + 2 * pad, H = c.h + 2 * pad;
        scratch.assign(static_cast<size_t>(W) * H, 0);
        for (int y = 0; y < c.h; ++y) {
            int sy = c.y + y;
            if (sy < 0 || sy >= page.h) continue;
            for (int x = 0; x < c.w; ++x) {
                int sx = c.x + x;
                if (sx < 0 || sx >= page.w) continue;
                scratch[static_cast<size_t>(y + pad) * W + x + pad] =
                    page.rgba[(static_cast<size_t>(sy) * page.w + sx) * 4 + 3];
            }
        }
        dilate(scratch, W, H, r, scratch2);
        return store(atlasFor(f), scratch2.data(), W, H,
                     c.xoffset - pad, c.yoffset - f.bm.base - pad);
    }

    int rasterSize(const FontData& f, float size) const {
        float px = f.filter == TextureFilter::Nearest ? size : size * outScale;
        return std::clamp(static_cast<int>(std::lround(px)), 1, MaxRasterPx);
    }

    GlyphQuad quad(FontData& f, uint32_t glyph, float size, float outlineWidth) {
        GlyphQuad q;
        if (f.bitmap) {
            float k = size / f.bm.size;
            q.unit = k;
            if (outlineWidth <= 0.f) {
                const BMFontDesc::Char& c = f.bm.chars.at(glyph);
                if (c.w <= 0 || c.h <= 0 || c.page < 0 || c.page >= static_cast<int>(f.pages.size())) return q;
                q.texture = f.pages[c.page];
                q.src = {static_cast<float>(c.x), static_cast<float>(c.y),
                         static_cast<float>(c.w), static_cast<float>(c.h)};
                q.offX = c.xoffset;
                q.offY = c.yoffset - f.bm.base;
                q.empty = false;
                return q;
            }
            int r = std::clamp(static_cast<int>(std::lround(outlineWidth / k)), 1, MaxOutlinePx);
            uint64_t key = glyphKey(f.key, glyph, 0, r);
            auto it = cache.find(key);
            if (it == cache.end()) it = cache.emplace(key, rasterBitmapOutline(f, glyph, r)).first;
            const CachedGlyph& e = it->second;
            q.texture = e.texture; q.src = e.src; q.offX = e.offX; q.offY = e.offY; q.empty = e.empty;
            return q;
        }
        int raster = rasterSize(f, size);
        q.unit = size / static_cast<float>(raster);
        int r = outlineWidth > 0.f
            ? std::clamp(static_cast<int>(std::lround(outlineWidth / q.unit)), 1, MaxOutlinePx) : 0;
        uint64_t key = glyphKey(f.key, glyph, raster, r);
        auto it = cache.find(key);
        if (it == cache.end()) it = cache.emplace(key, rasterTrueType(f, static_cast<int>(glyph), raster, r)).first;
        const CachedGlyph& e = it->second;
        q.texture = e.texture; q.src = e.src; q.offX = e.offX; q.offY = e.offY; q.empty = e.empty;
        return q;
    }

    // ---- drawing ----------------------------------------------------------

    // Output pixels per text unit: the window scale (unless the scene is
    // rendered at logical size), times the default camera's zoom for world
    // layers. TrueType glyphs are rasterized at size * outScale.
    void updateOutputScale(uint8_t layer) {
        float s = 1.f;
        if (renderer.scaleMode() != ScaleMode::Integer) {
            Rect o = renderer.outputRect();
            float lw = renderer.logicalWidth();
            if (o.w > 0.f && lw > 0.f) s = o.w / lw;
        }
        if (layer != ScreenLayer) s *= renderer.getCameraZoom(renderer.getDefaultCamera());
        outScale = std::clamp(s, 0.25f, 8.f);
    }

    void draw(FontData& primary, std::string_view text, const Transform2D& t, const TextStyle& st) {
        Layout& lay = drawLayout;
        layout(primary, text, st, lay);
        if (lay.glyphs.empty()) return;
        uint8_t layer = st.layer ? *st.layer : renderer.layer();
        updateOutputScale(layer);

        float top = st.valign == TextVAlign::Top ? 0.f
                  : st.valign == TextVAlign::Middle ? -lay.height * 0.5f : -lay.height;
        bool shadow = (st.shadowOffset.x != 0.f || st.shadowOffset.y != 0.f) && st.shadowColor.a > 0;
        bool outline = st.outlineWidth > 0.f && st.outlineColor.a > 0;

        // Passes: 0 shadow, 1 outline, 2 fill. Each sits just below the
        // next in zOrder so the sort keeps them in order across textures.
        for (int pass = 0; pass < 3; ++pass) {
            if ((pass == 0 && !shadow) || (pass == 1 && !outline)) continue;
            bool outlineShape = outline && pass != 2;
            for (size_t li = 0; li < lay.lines.size(); ++li) {
                const Line& line = lay.lines[li];
                float lx = st.align == TextAlign::Left ? 0.f
                         : st.align == TextAlign::Center ? -line.width * 0.5f : -line.width;
                float baseline = top + lay.ascent + static_cast<float>(li) * lay.lineAdvance;
                for (size_t gi = line.begin; gi < line.end; ++gi) {
                    const Shaped& g = lay.glyphs[gi];
                    if (g.space) continue;
                    GlyphQuad q = quad(*g.font, g.glyph, lay.size, outlineShape ? st.outlineWidth : 0.f);
                    if (q.empty) continue;
                    // Snap to the texture's pixel grid so glyphs stay sharp.
                    float inv = 1.f / q.unit;
                    float qx = (std::round((lx + g.x - line.x0) * inv) + q.offX) * q.unit;
                    float qy = (std::round(baseline * inv) + q.offY) * q.unit;
                    Color c = g.color;
                    float z = st.zOrder;
                    if (pass == 0) {
                        qx += st.shadowOffset.x;
                        qy += st.shadowOffset.y;
                        c = st.shadowColor;
                        c.a = static_cast<uint8_t>(c.a * g.color.a / 255);
                        z -= ShadowZBias;
                    } else if (pass == 1) {
                        c = st.outlineColor;
                        c.a = static_cast<uint8_t>(c.a * g.color.a / 255);
                        z -= OutlineZBias;
                    }
                    SpriteDraw d;
                    d.texture = q.texture;
                    d.srcRect = q.src;
                    d.scale = {q.unit * t.scale.x, q.unit * t.scale.y};
                    if (t.rotation == 0.f) {
                        // Unrotated text lands on whole output pixels even
                        // when its position is fractional.
                        d.position = {std::round((t.position.x + qx * t.scale.x) * outScale) / outScale,
                                      std::round((t.position.y + qy * t.scale.y) * outScale) / outScale};
                    } else {
                        d.position = t.position;
                        d.origin = {-qx * inv, -qy * inv};
                        d.rotation = t.rotation;
                    }
                    d.tint = c;
                    d.zOrder = z;
                    d.layer = layer;
                    renderer.draw(d);
                }
            }
        }
        linearAtlas.flush();
        nearestAtlas.flush();
    }
};

