// Decodes one UTF-8 sequence at s[i] and advances i. Malformed input
// yields U+FFFD and skips one byte.
uint32_t decodeUtf8(std::string_view s, size_t& i) {
    unsigned char c = static_cast<unsigned char>(s[i]);
    if (c < 0x80) { ++i; return c; }
    int len;
    uint32_t cp, min;
    if ((c & 0xE0) == 0xC0)      { len = 2; cp = c & 0x1F; min = 0x80; }
    else if ((c & 0xF0) == 0xE0) { len = 3; cp = c & 0x0F; min = 0x800; }
    else if ((c & 0xF8) == 0xF0) { len = 4; cp = c & 0x07; min = 0x10000; }
    else { ++i; return 0xFFFD; }
    if (i + len > s.size()) { ++i; return 0xFFFD; }
    for (int k = 1; k < len; ++k) {
        unsigned char cc = static_cast<unsigned char>(s[i + k]);
        if ((cc & 0xC0) != 0x80) { ++i; return 0xFFFD; }
        cp = (cp << 6) | (cc & 0x3F);
    }
    i += len;
    if (cp < min || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) return 0xFFFD;
    return cp;
}

int hexDigit(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

bool endsWithNoCase(std::string_view s, std::string_view suffix) {
    if (s.size() < suffix.size()) return false;
    for (size_t i = 0; i < suffix.size(); ++i) {
        char a = s[s.size() - suffix.size() + i];
        if (a >= 'A' && a <= 'Z') a = static_cast<char>(a - 'A' + 'a');
        if (a != suffix[i]) return false;
    }
    return true;
}

// Grows coverage by r pixels with an anti-aliased round brush.
void dilate(const std::vector<uint8_t>& src, int w, int h, int r, std::vector<uint8_t>& dst) {
    struct Tap { int dx, dy; float weight; };
    std::vector<Tap> taps;
    for (int dy = -r; dy <= r; ++dy) {
        for (int dx = -r; dx <= r; ++dx) {
            float weight = static_cast<float>(r) + 0.5f - std::sqrt(static_cast<float>(dx * dx + dy * dy));
            if (weight > 0.f) taps.push_back({dx, dy, std::min(weight, 1.f)});
        }
    }
    dst.assign(static_cast<size_t>(w) * h, 0);
    for (int y = 0; y < h; ++y) {
        for (int x = 0; x < w; ++x) {
            float best = 0.f;
            for (const Tap& t : taps) {
                int sx = x + t.dx, sy = y + t.dy;
                if (sx < 0 || sy < 0 || sx >= w || sy >= h) continue;
                float v = src[static_cast<size_t>(sy) * w + sx] * t.weight;
                if (v > best) best = v;
            }
            dst[static_cast<size_t>(y) * w + x] = static_cast<uint8_t>(best + 0.5f);
        }
    }
}

struct FontData {
    bool bitmap = false;
    float loadSize = 0.f;
    TextureFilter filter = TextureFilter::Linear;
    FontHandle fallback;
    uint32_t key = 0;   // handle index; part of glyph cache keys

    // TrueType
    std::vector<uint8_t> ttf;
    stbtt_fontinfo info{};
    float ascent = 0.f, descent = 0.f, lineGap = 0.f;   // font units
    std::unordered_map<uint32_t, int> glyphIndex;        // codepoint -> glyph

    // BMFont
    BMFontDesc bm;
    std::vector<TextureHandle> pages;
    struct PagePixels { int w = 0, h = 0; std::vector<uint8_t> rgba; };
    std::vector<PagePixels> pagePixels;
};

struct Metrics {
    float scale;        // font units (TrueType) or source pixels (BMFont) -> size units
    float ascent;       // baseline below the line top
    float lineHeight;
};

Metrics metricsFor(const FontData& f, float size) {
    if (f.bitmap) {
        float k = size / f.bm.size;
        return {k, f.bm.base * k, f.bm.lineHeight * k};
    }
    float s = stbtt_ScaleForPixelHeight(&f.info, size);
    return {s, f.ascent * s, (f.ascent - f.descent + f.lineGap) * s};
}

// A glyph after layout. x is the pen position within its unwrapped line.
struct Shaped {
    FontData* font;
    uint32_t glyph;     // TrueType glyph index, or BMFont codepoint
    float x;
    float advance;
    Color color;
    bool space;
};

struct Line {
    size_t begin, end;  // glyph range, trailing spaces excluded
    float width;
    float x0;           // pen x of the first glyph
};

struct Layout {
    std::vector<Shaped> glyphs;
    std::vector<Line> lines;
    float size = 0.f, ascent = 0.f, lineHeight = 0.f, lineAdvance = 0.f;
    float width = 0.f, height = 0.f;
};

// Where a glyph's pixels are and how they sit on the pen position.
struct GlyphQuad {
    TextureHandle texture;
    Rect src;
    float offX = 0.f, offY = 0.f;  // top-left of src from (pen, baseline), in texture pixels
    float unit = 1.f;              // size units per texture pixel
    bool empty = true;
};

struct CachedGlyph {
    TextureHandle texture;
    Rect src;
    float offX = 0.f, offY = 0.f;
    bool empty = true;
};

uint64_t glyphKey(uint32_t font, uint32_t glyph, int raster, int outline) {
    return (static_cast<uint64_t>(font & 0xFFFFF) << 44) |
           (static_cast<uint64_t>(glyph & 0x1FFFFF) << 23) |
           (static_cast<uint64_t>(raster & 0xFFF) << 8) |
           static_cast<uint64_t>(outline & 0xFF);
}

