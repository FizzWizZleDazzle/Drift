FontResource::FontResource(RendererResource& renderer)
    : impl_(new Impl(renderer)) {
    impl_->defaultFont = impl_->loadTrueType(fontdata::kDefaultFont, fontdata::kDefaultFontSize,
                                             DefaultFontSize, {}, "<default>");
}

FontResource::~FontResource() { delete impl_; }

FontHandle FontResource::loadFont(const char* path, float sizePx, FontOptions options) {
    if (!path) return {};
    size_t size = 0;
    void* data = SDL_LoadFile(path, &size);
    if (!data) {
        DRIFT_LOG_ERROR("loadFont: cannot read '%s': %s", path, SDL_GetError());
        return {};
    }
    FontHandle h;
    if (endsWithNoCase(path, ".fnt")) {
        h = impl_->loadBitmapFont(path, {static_cast<const char*>(data), size}, sizePx, options);
    } else {
        h = impl_->loadTrueType(static_cast<const uint8_t*>(data), size, sizePx, options, path);
    }
    SDL_free(data);
    return h;
}

FontHandle FontResource::loadFontFromMemory(const uint8_t* data, size_t size, float sizePx,
                                            FontOptions options) {
    return impl_->loadTrueType(data, size, sizePx, options, "<memory>");
}

void FontResource::destroyFont(FontHandle font) {
    if (!font.valid() || font == impl_->defaultFont) return;
    auto* p = impl_->fonts.get(font);
    if (!p) return;
    FontData& f = **p;
    for (TextureHandle t : f.pages) impl_->renderer.destroyTexture(t);
    for (auto it = impl_->cache.begin(); it != impl_->cache.end();) {
        if ((it->first >> 44) == f.key) it = impl_->cache.erase(it);
        else ++it;
    }
    impl_->fonts.destroy(font);
}

FontHandle FontResource::defaultFont() const { return impl_->defaultFont; }

void FontResource::setFallbackFont(FontHandle font, FontHandle fallback) {
    if (auto* p = impl_->fonts.get(font)) (*p)->fallback = fallback;
}

void FontResource::drawText(FontHandle font, std::string_view text, Vec2 position,
                            const TextStyle& style) {
    Transform2D t;
    t.position = position;
    drawText(font, text, t, style);
}

void FontResource::drawText(FontHandle font, std::string_view text, const Transform2D& transform,
                            const TextStyle& style) {
    FontData* f = impl_->get(font);
    if (!f || text.empty()) return;
    impl_->draw(*f, text, transform, style);
}

Vec2 FontResource::measureText(FontHandle font, std::string_view text, const TextStyle& style) const {
    FontData* f = impl_->get(font);
    if (!f || text.empty()) return {};
    Layout lay;
    impl_->layout(*f, text, style, lay);
    if (lay.lines.empty()) return {};
    return {lay.width, lay.height};
}

float FontResource::lineHeight(FontHandle font, float size) const {
    FontData* f = impl_->get(font);
    if (!f) return 0.f;
    return metricsFor(*f, size > 0.f ? size : f->loadSize).lineHeight;
}

void FontResource::beginFrame() {
    if (!impl_->linearAtlas.overBudget() && !impl_->nearestAtlas.overBudget()) return;
    DRIFT_LOG_DEBUG("font: glyph atlas over budget, rebuilding");
    impl_->linearAtlas.reset();
    impl_->nearestAtlas.reset();
    impl_->cache.clear();
}

